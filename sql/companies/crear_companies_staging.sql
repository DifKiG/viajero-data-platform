-- ============================================================
-- Compañías de Kommo: tabla de staging + fila de control
-- Se ejecuta UNA SOLA VEZ (seguro de repetir).
-- La fila de control arranca en el año 2000: la primera ejecución
-- del flujo 04_SYNC_COMPANIES trae TODAS las compañías.
-- ============================================================
CREATE TABLE IF NOT EXISTS staging.companies_raw (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id    bigint      NOT NULL,
  source_system varchar(50) NOT NULL DEFAULT 'kommo',
  payload       jsonb       NOT NULL,
  extracted_at  timestamp   NOT NULL DEFAULT now(),
  processed_at  timestamp,
  is_processed  boolean     NOT NULL DEFAULT false
);
CREATE INDEX IF NOT EXISTS idx_companies_raw_company ON staging.companies_raw (company_id);

INSERT INTO staging.sync_control (entity, last_sync)
VALUES ('companies', '2000-01-01 00:00:00')
ON CONFLICT (entity) DO NOTHING;